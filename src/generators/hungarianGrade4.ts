import {
  Exercise,
  HungarianChoiceExercise,
  HungarianTextInputExercise,
  HungarianTriadExercise,
} from '../types/curriculum';

function uid(prefix: string, idx: number): string {
  return `${prefix}-${idx}-${Math.random().toString(36).slice(2, 7)}`;
}

function shuffle<T>(arr: T[]): T[] {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

type QuestionTemplate =
  | Omit<HungarianChoiceExercise, 'id' | 'topicId'>
  | Omit<HungarianTextInputExercise, 'id' | 'topicId'>
  | Omit<HungarianTriadExercise, 'id' | 'topicId'>;

function instantiateTemplates(
  topicId: string,
  pool: QuestionTemplate[],
  count: number
): Exercise[] {
  const shuffled = shuffle(pool);
  const result: Exercise[] = [];
  for (let i = 0; i < count; i++) {
    const tpl = shuffled[i % shuffled.length];
    if (tpl.kind === 'hu-choice') {
      result.push({
        ...tpl,
        options: shuffle(tpl.options),
        id: uid(topicId, i),
        topicId,
      });
    } else {
      result.push({
        ...tpl,
        id: uid(topicId, i),
        topicId,
      } as Exercise);
    }
  }
  return result;
}

